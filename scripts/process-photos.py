"""Turn the original job photos into web-ready WebP files.

    python3 scripts/process-photos.py manifest.json

manifest.json maps each slug to its original file plus optional privacy blurs:
  {"velux-loft-room": {"src": "/path/IMG_1234.jpg", "blur": [[x0, y0, x1, y1], ...]}}
Blur boxes are fractions (0-1) of the image width and height. Number plates and
house names/numbers should always be blurred.

Writes assets/img/photos/<slug>-<width>.webp at 640px and 1280px wide (or the
original width if smaller), strips EXIF/GPS, and regenerates src/photo-sizes.js.
"""
import json, sys
from pathlib import Path
from PIL import Image, ImageOps, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets/img/photos'
WIDTHS = (640, 1280)

manifest = json.load(open(sys.argv[1]))
OUT.mkdir(parents=True, exist_ok=True)
sizes = {}
for slug, m in manifest.items():
    im = ImageOps.exif_transpose(Image.open(m['src'])).convert('RGB')
    W, H = im.size
    for x0, y0, x1, y1 in m.get('blur', []):
        box = (int(x0 * W), int(y0 * H), int(x1 * W), int(y1 * H))
        region = im.crop(box).resize((6, 3)).resize((box[2] - box[0], box[3] - box[1]), Image.NEAREST)
        im.paste(region.filter(ImageFilter.GaussianBlur(4)), box)
    widths = sorted({min(w, W) for w in WIDTHS})
    for w in widths:
        h = round(H * w / W)
        im.resize((w, h), Image.LANCZOS).save(OUT / f'{slug}-{w}.webp', 'WEBP', quality=74, method=6)
    sizes[slug] = {'w': W, 'h': H, 'widths': widths}
    print(slug, W, H, widths)

(ROOT / 'src/photo-sizes.js').write_text(
    '// Generated by scripts/process-photos.py. Do not edit by hand.\n'
    f'export const photoSizes = {json.dumps(sizes, indent=1)};\n')
